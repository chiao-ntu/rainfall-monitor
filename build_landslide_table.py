# 官方小計（用於自檢）
SUBTOTAL = {"宜蘭縣":3,"新北市":3,"桃園市":5,"新竹縣":7,"苗栗縣":5,"臺中市":13,
            "南投縣":8,"嘉義縣":10,"高雄市":11,"屏東縣":5,"臺東縣":13,"花蓮縣":11}
TOTAL = 94


def stn_norm(name: str) -> str:
    """站名正規化：全形→半形、去尾端機關代碼字母、去尾端 (數字) 或 空白數字。
    須與 fetch_rainfall.py 的 _stn_key() 行為一致（該函式僅去尾端字母），
    故此處額外輸出 station_key（去括號數字）供第二層比對。"""
    s = unicodedata.normalize('NFKC', (name or '')).strip()
    prev = None
    while prev != s:
        prev = s
        s = re.sub(r'[A-Za-z]+$', '', s).strip()
        s = re.sub(r'\(\s*\d+\s*\)$', '', s).strip()
        s = re.sub(r'\s+\d+$', '', s).strip()
    return s


def stn_plain(name: str) -> str:
    """僅做全形→半形，保留原樣（第一層精確比對用，對應 SWCB API 的 STName）。"""
    return unicodedata.normalize('NFKC', (name or '')).strip()


def main():
    zones, seen_ids = [], set()
    by_county = {}
    for (cty, town, vill, n, alert, s1, s2, forest, ids, note) in ROWS:
        for i in ids:
            assert i not in seen_ids, f"重複編號 {i}"
            seen_ids.add(i)
        assert len(ids) == 0 or len(ids) == n, f"{cty}{town}{vill} 編號數({len(ids)})≠潛勢區數({n})"
        zones.append({
            "county": cty, "town": town, "village": vill,
            "n_zones": n, "alert": alert,
            "ids": ids,                       # 空陣列＝以 (縣市,鄉鎮,村里) 匹配該村里未被顯式認領的潛勢區
            "station1": stn_plain(s1), "station2": stn_plain(s2),
            "station1_norm": stn_norm(s1), "station2_norm": stn_norm(s2),
            "forest_bureau": forest,          # ◎ 屬林業保育署權責
            "note": note,                     # * 因應土石流警戒值調整作業調整
        })
        by_county[cty] = by_county.get(cty, 0) + n

    # 自檢
    assert by_county == SUBTOTAL, f"縣市小計不符：{by_county}"
    assert sum(by_county.values()) == TOTAL, f"總數不符：{sum(by_county.values())}"

    out = {
        "description": "官方大規模崩塌警戒-逐警戒區(代表站+雨量警戒基準值)，比照 slope_warning_stations.json 結構",
        "source": "115年大規模崩塌潛勢區雨量警戒基準值明細表（115年1月更新，農業部農村發展及水土保持署）",
        "source_url": "https://246.ardswc.gov.tw/Landslide/AlertTable",
        "note": ("ETR2 即時值由代表站取得（水保署 API 優先，CWA 觀測備援）；"
                 "警戒值為官方公告值。ids 為空者以 (縣市,鄉鎮,村里) 匹配 landslide_geo.json，"
                 "顯式 ids 優先認領。station 為原名（精確比對），station_norm 為正規化名（備援比對）。"),
        "legend": {"forest_bureau": "◎ 屬林業保育署權責",
                   "note": "* 雨量警戒基準值因應土石流警戒值調整作業調整",
                   "station_suffix": "s=農村水保署 w=水利署 f=林業保育署 sr=石門水庫管理中心 fr=翡翠水庫管理局（無後綴＝氣象署）"},
        "total_zones": TOTAL,
        "county_subtotal": SUBTOTAL,
        "zones": zones,
    }
    with open("landslide_warning_stations.json", "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)

    print(f"OK  {len(zones)} 列 / {TOTAL} 處潛勢區")
    print(f"顯式編號 {len(seen_ids)} 個：{sorted(seen_ids)}")
    print(f"縣市小計自檢通過：{by_county}")
    # 正規化有變動的站名一覽（供人工核對）
    print("\n站名正規化有變動者：")
    for z in zones:
        for k in ("1", "2"):
            p, q = z["station"+k], z["station"+k+"_norm"]
            if p != q:
                print(f"  {p!r} → {q!r}")


if __name__ == "__main__":
    main()
